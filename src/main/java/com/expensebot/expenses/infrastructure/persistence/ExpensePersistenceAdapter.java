package com.expensebot.expenses.infrastructure.persistence;

import com.expensebot.accounts.Channel;
import com.expensebot.expenses.RegisteredExpense;
import com.expensebot.expenses.application.ExpenseRepository;
import com.expensebot.expenses.domain.Expense;
import com.expensebot.expenses.domain.Money;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Repository;

import java.sql.Date;
import java.time.Instant;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.Currency;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

@Repository
public class ExpensePersistenceAdapter implements ExpenseRepository {
    private final JdbcClient jdbcClient;

    public ExpensePersistenceAdapter(JdbcClient jdbcClient) {
        this.jdbcClient = jdbcClient;
    }

    // Plain INSERT on purpose: the id is generated by the domain, and with JPA a pre-assigned id makes Spring Data
    // run a SELECT first to decide between insert and update. created_at / updated_at use the column defaults.
    @Override
    public void save(Expense expense) {
        jdbcClient
                .sql("INSERT INTO expense (id, user_id, category_id, amount, currency, description, spent_on, "
                        + "source_channel, original_message) "
                        + "VALUES (:id, :userId, :categoryId, :amount, :currency, :description, :spentOn, "
                        + ":sourceChannel, :originalMessage)")
                .param("id", expense.getId())
                .param("userId", expense.getUserId())
                .param("categoryId", expense.getCategoryId())
                .param("amount", expense.getMoney().amount())
                .param("currency", expense.getMoney().currency().getCurrencyCode())
                .param("description", expense.getDescription())
                .param("spentOn", Date.valueOf(expense.getSpentOn()))
                .param("sourceChannel", expense.getSourceChannel().name())
                .param("originalMessage", expense.getOriginalMessage())
                .update();
    }

    // Filtering by user in the query (not after loading) keeps another user's expense out of reach by construction.
    @Override
    public Optional<Expense> findByIdAndUserId(UUID id, UUID userId) {
        return jdbcClient
                .sql("SELECT id, user_id, category_id, amount, currency, description, spent_on, source_channel, "
                        + "original_message FROM expense WHERE id = :id AND user_id = :userId")
                .param("id", id)
                .param("userId", userId)
                .query((rs, rowNum) -> Expense.restore(
                        rs.getObject("id", UUID.class),
                        rs.getObject("user_id", UUID.class),
                        rs.getObject("category_id", UUID.class),
                        new Money(rs.getBigDecimal("amount"), Currency.getInstance(rs.getString("currency"))),
                        rs.getString("description"),
                        rs.getObject("spent_on", LocalDate.class),
                        Channel.valueOf(rs.getString("source_channel")),
                        rs.getString("original_message")))
                .optional();
    }

    // Only the editable columns: even if a bug changed another field in memory, the stored record keeps it.
    @Override
    public void update(Expense expense) {
        int updated = jdbcClient
                .sql("UPDATE expense SET category_id = :categoryId, amount = :amount, description = :description, "
                        + "updated_at = now() WHERE id = :id")
                .param("id", expense.getId())
                .param("categoryId", expense.getCategoryId())
                .param("amount", expense.getMoney().amount())
                .param("description", expense.getDescription())
                .update();
        if (updated != 1) {
            throw new IllegalStateException("Expense to update not found: " + expense.getId());
        }
    }

    // "Recent" is when the row was stored (created_at), not the expense date: a correction refers to what the bot
    // just confirmed. The id breaks ties so the order is stable when two rows share a timestamp.
    @Override
    public List<RegisteredExpense> findRecent(UUID userId, Channel channel, Instant since) {
        return jdbcClient
                .sql("SELECT e.id, e.amount, e.currency, e.description, c.name AS category_name, e.spent_on "
                        + "FROM expense e JOIN category c ON c.id = e.category_id "
                        + "WHERE e.user_id = :userId AND e.source_channel = :channel AND e.created_at >= :since "
                        + "ORDER BY e.created_at DESC, e.id DESC")
                .param("userId", userId)
                .param("channel", channel.name())
                // The PostgreSQL driver binds OffsetDateTime to TIMESTAMPTZ; it has no mapping for Instant.
                .param("since", OffsetDateTime.ofInstant(since, ZoneOffset.UTC))
                .query((rs, rowNum) -> new RegisteredExpense(
                        rs.getObject("id", UUID.class),
                        rs.getBigDecimal("amount"),
                        rs.getString("currency"),
                        rs.getString("description"),
                        rs.getString("category_name"),
                        rs.getObject("spent_on", LocalDate.class)))
                .list();
    }
}
